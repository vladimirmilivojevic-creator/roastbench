package dev.roastbench.demo;

import dev.roastbench.analysis.EventType;
import dev.roastbench.analysis.RoastCurve;
import dev.roastbench.demo.SyntheticRoastGenerator.GeneratedRoast;
import java.time.Instant;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.Locale;
import java.util.Map;
import java.util.StringJoiner;

/** Writes a generated roast as CSV, or as an Artisan style .alog file. */
public final class SampleFormats {

    /** Preheat samples written before charge in the {@code .alog} sample, like a real Artisan recording. */
    private static final int PRE_CHARGE_SAMPLES = 6;

    private SampleFormats() {
    }

    public record Meta(String title, String beans, String machine, Instant roastedAt) {
    }

    public static String toCsv(GeneratedRoast roast, Meta meta) {
        RoastCurve curve = roast.curve();
        double[] t = curve.timeSeconds();
        double[] bt = curve.beanTemp();
        double[] et = curve.envTemp();
        double drop = roast.events().get(EventType.DROP);

        StringBuilder sb = new StringBuilder();
        sb.append("# Synthetic sample roast generated by RoastBench. Not a real roast.\n");
        sb.append("# title: ").append(meta.title()).append('\n');
        sb.append("# beans: ").append(meta.beans()).append('\n');
        sb.append("# machine: ").append(meta.machine()).append('\n');
        sb.append("# date: ").append(DateTimeFormatter.ISO_INSTANT.format(meta.roastedAt())).append('\n');
        sb.append("# green_weight_g: ").append(num(roast.greenWeightG())).append('\n');
        sb.append("# roasted_weight_g: ").append(num(roast.roastedWeightG())).append('\n');
        sb.append("Time (s),BT (C),ET (C),Event\n");
        for (int i = 0; i < t.length && t[i] <= drop; i++) {
            sb.append(num(t[i])).append(',').append(num(bt[i])).append(',').append(num(et[i])).append(',')
                    .append(eventLabelAt(roast.events(), t[i], i == 0)).append('\n');
        }
        return sb.toString();
    }

    /**
     * Artisan-style profile: Python dict literal with single quotes, preheat samples before charge, {@code timeindex}
     * with CHARGE, DRY, FCs, FCe, SCs, SCe, DROP, COOL, and cooling samples after drop. The generated roast must have
     * been created with cooling samples.
     */
    public static String toAlog(GeneratedRoast roast, Meta meta) {
        RoastCurve curve = roast.curve();
        double[] rel = curve.timeSeconds();
        double[] bt = curve.beanTemp();
        double[] et = curve.envTemp();
        double interval = rel[1] - rel[0];
        int n = PRE_CHARGE_SAMPLES + rel.length;

        StringJoiner timex = new StringJoiner(", ", "[", "]");
        StringJoiner temp1 = new StringJoiner(", ", "[", "]");
        StringJoiner temp2 = new StringJoiner(", ", "[", "]");
        for (int i = 0; i < n; i++) {
            timex.add(num(i * interval));
            if (i < PRE_CHARGE_SAMPLES) { // drum preheated, probe reads the empty drum
                temp1.add(num(et[0] + 2.0));
                temp2.add(num(bt[0]));
            } else {
                temp1.add(num(et[i - PRE_CHARGE_SAMPLES]));
                temp2.add(num(bt[i - PRE_CHARGE_SAMPLES]));
            }
        }

        Map<EventType, Double> ev = roast.events();
        int[] timeIndex = {PRE_CHARGE_SAMPLES, index(ev, EventType.DRY_END, interval), index(ev,
                EventType.FIRST_CRACK_START, interval), index(ev, EventType.FIRST_CRACK_END, interval), 0, 0,
                index(ev, EventType.DROP, interval), index(ev, EventType.COOL, interval)};
        StringJoiner idx = new StringJoiner(", ", "[", "]");
        for (int i : timeIndex) {
            idx.add(Integer.toString(i));
        }

        double drop = ev.get(EventType.DROP);
        StringBuilder sb = new StringBuilder("{");
        sb.append("'recording_version': '3.1.0', 'viewerMode': False, 'mode': 'C', ");
        sb.append("'title': '").append(escape(meta.title())).append("', ");
        sb.append("'beans': '").append(escape(meta.beans())).append("', ");
        sb.append("'roastertype': '").append(escape(meta.machine())).append("', ");
        sb.append("'roastisodate': '").append(meta.roastedAt().atOffset(ZoneOffset.UTC).toLocalDate()).append("', ");
        sb.append("'roasttime': '").append(String.format(Locale.ROOT, "%02d:%02d:%02d",
                meta.roastedAt().atOffset(ZoneOffset.UTC).getHour(), meta.roastedAt().atOffset(ZoneOffset.UTC).getMinute(),
                meta.roastedAt().atOffset(ZoneOffset.UTC).getSecond())).append("', ");
        sb.append("'roastepoch': ").append(meta.roastedAt().getEpochSecond()).append(", ");
        sb.append("'weight': [").append(num(roast.greenWeightG())).append(", ").append(num(roast.roastedWeightG()))
                .append(", 'g'], ");
        sb.append("'samplinginterval': ").append(num(interval)).append(", ");
        sb.append("'timex': ").append(timex).append(", ");
        sb.append("'temp1': ").append(temp1).append(", ");
        sb.append("'temp2': ").append(temp2).append(", ");
        sb.append("'timeindex': ").append(idx).append(", ");
        sb.append("'specialevents': [], 'specialeventstype': [], 'specialeventsvalue': [], 'specialeventsStrings': [], ");
        sb.append("'computed': {'DROP_time': ").append(num(drop)).append(", 'totaltime': ").append(num(drop))
                .append("}, ");
        sb.append("'plus_store': None}");
        return sb.toString();
    }

    private static int index(Map<EventType, Double> events, EventType type, double interval) {
        return PRE_CHARGE_SAMPLES + (int) Math.round(events.get(type) / interval);
    }

    private static String eventLabelAt(Map<EventType, Double> events, double t, boolean first) {
        if (first) {
            return "Charge";
        }
        for (Map.Entry<EventType, Double> e : events.entrySet()) {
            if (Math.abs(e.getValue() - t) < 1e-9) {
                return switch (e.getKey()) {
                    case DRY_END -> "Dry End";
                    case FIRST_CRACK_START -> "FC Start";
                    case FIRST_CRACK_END -> "FC End";
                    case DROP -> "Drop";
                    default -> "";
                };
            }
        }
        return "";
    }

    private static String num(double v) {
        return String.format(Locale.ROOT, "%.1f", v);
    }

    private static String escape(String s) {
        return s.replace("\\", "\\\\").replace("'", "\\'");
    }
}
